async (page) => {
  page.setDefaultTimeout(10000);
  const checks=[];
  const check=(condition,label)=>{if(!condition)throw new Error(label);checks.push(label);};
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.evaluate(()=>localStorage.removeItem('hacky-style-v1'));
  await page.reload();
  await page.locator('.mascot-stage .hacky-pet').waitFor();
  check(await page.locator('#sidebar').evaluate(el=>el.inert),'Phone chats start hidden');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Phone has no horizontal overflow');
  await page.screenshot({path:'verification/phone.png',scale:'css'});
  await page.getByRole('button',{name:'Meet mentors',exact:true}).click();
  await page.getByRole('button',{name:'View Aya Patel profile, Mentor',exact:true}).waitFor();
  check(await page.locator('.match').count()===5,'Mentor results offer five compact cards');
  check(await page.locator('.match').first().innerText().then(t=>t.includes('Mentor')),'Security result identifies mentor');
  await page.getByRole('button',{name:'View Aya Patel profile, Mentor',exact:true}).click();
  check(await page.locator('#person-dialog').evaluate(el=>el.open),'Card opens expanded profile');
  check(await page.locator('#person-dialog .social-notice').innerText().then(t=>t.includes('Demo links unavailable')),'Unavailable social accounts are disclosed before interaction');
  check(await page.locator('#person-dialog .social-link').first().isDisabled(),'Unavailable social links are disabled');
  await page.locator('#person-message').click();
  check(await page.locator('#main').evaluate(el=>el.inert),'Open phone drawer makes finder inert');
  await page.locator('#dm-input').fill('Can you review our auth?');
  await page.locator('#dm-send').click();
  await page.locator('#dm-feed .bubble').filter({hasText:'Hey! Happy to help with security. What does your app do?'}).waitFor();
  checks.push('Direct message and sample reply work');
  await page.locator('#dm-input').fill('Keep this draft');
  await page.locator('#back-list').click();
  await page.locator('[data-contact="aya"]').click();
  check(await page.locator('#dm-input').inputValue()==='Keep this draft','Draft survives conversation navigation');
  check(await page.locator('#dm-input').evaluate(el=>document.activeElement!==el),'Opening a chat does not focus the composer');
  check(await page.locator('#dm-role').innerText()==='Mentor','Chat header preserves category label');
  await page.locator('#dm-input').fill('A long message for scroll testing. '.repeat(60));
  await page.locator('#dm-send').click();
  await page.locator('#dm-feed').evaluate(el=>el.scrollTop=0);
  await page.locator('#new-reply').waitFor({state:'visible'});
  check(await page.locator('#dm-feed').evaluate(el=>el.scrollTop)<10,'Incoming reply preserves older reading position');
  await page.locator('#new-reply').click();
  check(await page.locator('#dm-feed').evaluate(el=>el.scrollHeight-el.scrollTop-el.clientHeight)<2,'New reply action reaches the latest message');
  await page.getByRole('button',{name:'Back to chats',exact:true}).click();
  await page.locator('#team').click();
  await page.locator('#dm-input').fill('Found a security mentor.');
  await page.locator('#dm-send').click();
  await page.locator('#dm-feed .bubble').filter({hasText:'Sounds good! Send the matches here and we can meet them.'}).waitFor();
  checks.push('Team message and sample reply work');
  await page.locator('#back-list').click();
  await page.getByRole('button',{name:'Return to finder',exact:true}).click();
  await page.locator('#finder-input').fill('Find a designer for our team');
  await page.locator('#finder-send').click();
  await page.getByRole('button',{name:'View Jules Park profile, Hacker',exact:true}).waitFor();
  checks.push('Design matching works');
  await page.locator('#finder-input').fill('Find a sponsor who can help with APIs');
  await page.locator('#finder-send').click();
  await page.getByRole('button',{name:'View Sasha Rivera profile, Sponsor',exact:true}).waitFor();
  check(await page.locator('.match').last().innerText().then(t=>t.includes('Sponsor')),'Sponsor request surfaces a sponsor');
  await page.getByRole('button',{name:'Style Hacky',exact:true}).click();
  await page.getByRole('button',{name:'Cyber Cat',exact:true}).click();
  check(await page.locator('#save-status').innerText()==='Unsaved changes. Close to discard.','Unsaved companion preview is labeled');
  await page.waitForLoadState('networkidle');
  await page.screenshot({path:'verification/customizer-phone.png',scale:'css'});
  await page.getByRole('button',{name:'Discard changes and close customization',exact:true}).click();
  check(await page.locator('.mascot-stage .hacky-pet').evaluate(el=>el.style.getPropertyValue('--pet-url').includes('classic')),'Cancel preserves applied companion');
  await page.getByRole('button',{name:'Style Hacky',exact:true}).click();
  await page.getByRole('button',{name:'Cyber Cat',exact:true}).click();
  await page.getByRole('tab',{name:'Color',exact:true}).click();
  await page.getByRole('button',{name:'Mint',exact:true}).click();
  await page.getByRole('tab',{name:'Moves',exact:true}).click();
  await page.getByRole('button',{name:'Happy dance',exact:true}).click();
  await page.getByRole('button',{name:'Save Hacky',exact:true}).click();
  await page.reload();
  check(await page.locator('.mascot-stage .hacky-pet').evaluate(el=>el.style.getPropertyValue('--pet-url').includes('cat')&&el.dataset.move==='dance'),'Saved companion persists after reload');
  await page.emulateMedia({reducedMotion:'reduce'});
  check(await page.locator('.mascot-stage .pet-sprite').evaluate(el=>getComputedStyle(el).animationName)==='none','Reduced motion stops companion animation');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.evaluate(()=>localStorage.removeItem('hacky-style-v1'));
  await page.reload();
  const desktop=await page.context().browser().newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'});
  const wide=await desktop.newPage();
  wide.on('pageerror',error=>errors.push(error.message));
  await wide.goto('http://127.0.0.1:4173');
  await wide.locator('.mascot-stage .hacky-pet').waitFor();
  check(await wide.locator('#sidebar').isVisible(),'Desktop chats start visible');
  check(await wide.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desktop has no horizontal overflow');
  await wide.screenshot({path:'verification/desktop.png',scale:'css'});
  await wide.getByRole('button',{name:'Style Hacky',exact:true}).click();
  await wide.waitForLoadState('networkidle');
  await wide.screenshot({path:'verification/customizer-desktop.png',scale:'css'});
  await wide.getByRole('tab',{name:'Looks',exact:true}).focus();
  await wide.keyboard.press('ArrowRight');
  check(await wide.getByRole('tab',{name:'Color',exact:true}).getAttribute('aria-selected')==='true','Customizer tabs support keyboard navigation');
  await wide.keyboard.press('Escape');
  await wide.waitForFunction(()=>!document.querySelector('dialog').open&&document.activeElement.id==='style-hacky');
  check(await wide.locator('#style-hacky').evaluate(el=>document.activeElement===el),'Customizer returns keyboard focus');
  await desktop.close();
  await page.setViewportSize({width:320,height:640});
  await page.reload();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Small phone has no horizontal overflow');
  await page.screenshot({path:'verification/small-phone.png',scale:'css'});
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:4173/event-demo/knight-hacks-demo.html');
  const entry=page.locator('a[href="../index.html"]');
  check(await entry.count()>0,'Event entry links to Hacky');
  await entry.first().click();
  await page.locator('#finder-form').waitFor();
  checks.push('Event link opens Hacky');
  check(errors.length===0,'No JavaScript page errors');
  return {browser:'WebKit',checks,errors};
}
